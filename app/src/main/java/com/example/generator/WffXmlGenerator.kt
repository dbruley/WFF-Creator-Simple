package com.example.generator

import com.example.model.ClockType
import com.example.model.ComplicationPosition
import com.example.model.ComplicationSlotConfig
import com.example.model.ComplicationType
import com.example.model.HandMotion
import com.example.model.SimulatedDataSource
import com.example.model.WatchFaceConfig
import com.example.model.WatchShape

object WffXmlGenerator {

    fun generateWatchFaceXml(config: WatchFaceConfig): String {
        val wffVersion = when (config.targetWearOsVersion) {
            4 -> "1"
            5 -> "2"
            6 -> "3"
            else -> "4" // Wear OS 7
        }
        val clipShape = if (config.shape.isCircular) "CIRCLE" else "RECTANGLE"
        val sb = StringBuilder()

        sb.appendLine("""<?xml version="1.0" encoding="utf-8"?>""")
        sb.appendLine("""<!-- Generated by Wear OS Watch Face Studio -->""")
        sb.appendLine("""<!-- Target: Wear OS ${config.targetWearOsVersion} (Watch Face Format v$wffVersion) -->""")
        sb.appendLine(
            """<WatchFace width="${config.shape.sizeDp}" height="${config.shape.sizeDp}" clipShape="$clipShape""""
        )
        sb.appendLine("""    xmlns:android="http://schemas.android.com/apk/res/android"""")
        sb.appendLine("""    xmlns:wff="http://schemas.android.com/wear/watchface/format">""")

        // Metadata
        sb.appendLine()
        sb.appendLine("""    <!-- Engine Metadata -->""")
        sb.appendLine("""    <Metadata key="CLOCK_TYPE" value="${config.clockType.name}" />""")
        sb.appendLine("""    <Metadata key="PREVIEW_TIME" value="10:08:32" />""")
        sb.appendLine("""    <Metadata key="TARGET_WEAR_OS_VERSION" value="${config.targetWearOsVersion}" />""")
        sb.appendLine("""    <Metadata key="WFF_VERSION" value="$wffVersion" />""")
        sb.appendLine("""    <Metadata key="AUTHOR" value="Watch Face Studio" />""")
        sb.appendLine("""    <Metadata key="NAME" value="${escapeXml(config.name)}" />""")

        // UserConfigurations & Flavors (Wear OS 5+)
        if (config.targetWearOsVersion >= 5) {
            sb.appendLine()
            sb.appendLine("""    <!-- User Customization Configurations (Wear OS 5+) -->""")
            sb.appendLine("""    <UserConfigurations>""")
            sb.appendLine("""        <ColorConfiguration id="theme_palette" displayName="Theme Palette" defaultValue="0">""")
            config.availableFlavors.forEachIndexed { index, flavor ->
                sb.appendLine(
                    """            <ColorOption id="$index" displayName="${escapeXml(flavor.displayName)}" colors="${flavor.primaryColor} ${flavor.secondaryColor}" />"""
                )
            }
            sb.appendLine("""        </ColorConfiguration>""")

            sb.appendLine("""        <BooleanConfiguration id="show_seconds" displayName="Show Second Hand" defaultValue="${if (config.analogHands.secondHandVisible) "TRUE" else "FALSE"}" />""")
            sb.appendLine("""        <ListConfiguration id="dial_bezel_style" displayName="Bezel Style" defaultValue="${config.bezelStyle.name.lowercase()}">""")
            sb.appendLine("""            <ListOption id="diver_60" displayName="Diver Bezel" />""")
            sb.appendLine("""            <ListOption id="cardinal_numerals" displayName="Cardinal 12-3-6-9" />""")
            sb.appendLine("""            <ListOption id="minimal_ticks" displayName="Minimal Indices" />""")
            sb.appendLine("""            <ListOption id="none" displayName="Clean Rimless" />""")
            sb.appendLine("""        </ListConfiguration>""")
            sb.appendLine("""    </UserConfigurations>""")
        }

        // Wear OS 7 Multi-tier Flavors
        if (config.targetWearOsVersion >= 7) {
            sb.appendLine()
            sb.appendLine("""    <!-- Wear OS 7 Pre-Packaged Flavors -->""")
            sb.appendLine("""    <Flavors>""")
            config.availableFlavors.forEachIndexed { index, flavor ->
                sb.appendLine("""        <Flavor id="${flavor.id}" displayName="${escapeXml(flavor.displayName)}">""")
                sb.appendLine("""            <Configuration id="theme_palette" optionId="$index" />""")
                sb.appendLine("""            <Configuration id="show_seconds" optionId="TRUE" />""")
                sb.appendLine("""        </Flavor>""")
            }
            sb.appendLine("""    </Flavors>""")
        }

        // Scene
        sb.appendLine()
        sb.appendLine("""    <!-- Visual Scene & Layers -->""")
        sb.appendLine("""    <Scene backgroundColor="#000000">""")

        // Dial Background & Rim
        sb.appendLine("""        <!-- Dial Background -->""")
        val half = config.shape.sizeDp / 2
        val radius = half - 6
        sb.appendLine("""        <PartDraw x="0" y="0" width="${config.shape.sizeDp}" height="${config.shape.sizeDp}">""")
        sb.appendLine("""            <Circle x="$half" y="$half" radius="$radius">""")
        sb.appendLine("""                <Fill color="#0B0F19" />""")
        sb.appendLine("""                <Stroke color="${config.bezelColor}" thickness="3" />""")
        sb.appendLine("""            </Circle>""")

        if (config.innerRingVisible) {
            sb.appendLine("""            <!-- Inner Accent Ring -->""")
            sb.appendLine("""            <Circle x="$half" y="$half" radius="${radius - 32}">""")
            sb.appendLine("""                <Stroke color="${config.innerRingColor}" thickness="1.5" />""")
            sb.appendLine("""            </Circle>""")
        }

        // Ticks/indices
        sb.appendLine("""            <!-- Bezel Indices: ${config.bezelStyle.displayName} -->""")
        sb.appendLine("""            <!-- WFF Native TickMarks Element -->""")
        sb.appendLine("""            <TickMarks x="0" y="0" width="${config.shape.sizeDp}" height="${config.shape.sizeDp}">""")
        sb.appendLine("""                <TickMark count="60" color="${config.themeColor}" length="6" thickness="1.2" />""")
        sb.appendLine("""                <TickMark count="12" color="${config.secondaryColor}" length="12" thickness="3" />""")
        sb.appendLine("""            </TickMarks>""")
        sb.appendLine("""        </PartDraw>""")

        // Complication Slots
        sb.appendLine()
        sb.appendLine("""        <!-- Complication Slots -->""")
        config.complications.filter { it.enabled }.forEach { slot ->
            generateComplicationSlotXml(sb, slot, config)
        }

        // Digital Clock component (if DIGITAL or HYBRID)
        if (config.clockType == ClockType.DIGITAL || config.clockType == ClockType.HYBRID) {
            sb.appendLine()
            sb.appendLine("""        <!-- Digital Clock Engine -->""")
            val boxHeight = (config.digitalClock.fontSize * 1.35f).toInt().coerceAtLeast(48)
            val digY = half - (boxHeight / 2) + config.digitalClock.positionYOffset.toInt()
            val hourPattern = if (config.digitalClock.is24Hour) {
                if (config.digitalClock.leadingZero) "HH" else "H"
            } else {
                if (config.digitalClock.leadingZero) "hh" else "h"
            }
            val formatStr = if (config.digitalClock.showSeconds) {
                "$hourPattern:mm:ss"
            } else {
                "$hourPattern:mm"
            }
            sb.appendLine("""        <DigitalClock x="45" y="$digY" width="360" height="$boxHeight">""")
            sb.appendLine("""            <TimeText format="$formatStr">""")
            sb.appendLine("""                <Font family="${config.digitalClock.fontFamily.name}" size="${config.digitalClock.fontSize}" color="${config.digitalClock.minuteColor}" weight="BOLD" />""")
            sb.appendLine("""            </TimeText>""")
            if (config.digitalClock.showDate) {
                sb.appendLine("""            <DateText format="${config.digitalClock.dateFormat}">""")
                sb.appendLine("""                <Font size="14" color="${config.digitalClock.dateColor}" />""")
                sb.appendLine("""            </DateText>""")
            }
            sb.appendLine("""        </DigitalClock>""")
        }

        // Analog Clock component (if ANALOG or HYBRID)
        if (config.clockType == ClockType.ANALOG || config.clockType == ClockType.HYBRID) {
            sb.appendLine()
            sb.appendLine("""        <!-- Analog Clock Engine -->""")
            sb.appendLine("""        <AnalogClock x="0" y="0" width="${config.shape.sizeDp}" height="${config.shape.sizeDp}">""")

            // Hour Hand
            sb.appendLine("""            <!-- Hour Hand -->""")
            sb.appendLine("""            <HourHand resource="hour_hand" pivotX="0.5" pivotY="0.5">""")
            sb.appendLine("""                <HandDraw length="${(radius * config.analogHands.hourHandLength).toInt()}" width="${config.analogHands.hourHandWidth.toInt()}" color="${config.analogHands.hourHandColor}">""")
            sb.appendLine("""                    <Cap type="ROUND" />""")
            sb.appendLine("""                </HandDraw>""")
            sb.appendLine("""            </HourHand>""")

            // Minute Hand
            sb.appendLine("""            <!-- Minute Hand -->""")
            sb.appendLine("""            <MinuteHand resource="minute_hand" pivotX="0.5" pivotY="0.5">""")
            sb.appendLine("""                <HandDraw length="${(radius * config.analogHands.minuteHandLength).toInt()}" width="${config.analogHands.minuteHandWidth.toInt()}" color="${config.analogHands.minuteHandColor}">""")
            sb.appendLine("""                    <Cap type="ROUND" />""")
            sb.appendLine("""                </HandDraw>""")
            sb.appendLine("""            </MinuteHand>""")

            // Second Hand (Auto-hidden in Ambient mode per Wear OS specifications)
            if (config.analogHands.secondHandVisible) {
                val motionAttr = if (config.analogHands.secondHandMotion == HandMotion.SWEEP) "SWEEP" else "STEP"
                sb.appendLine("""            <!-- Second Hand: Power optimized - automatically hidden in Ambient / AOD mode -->""")
                sb.appendLine("""            <Compare expression="[IS_AMBIENT] == 0">""")
                sb.appendLine("""                <SecondHand resource="second_hand" pivotX="0.5" pivotY="0.5" motion="$motionAttr">""")
                sb.appendLine("""                    <HandDraw length="${(radius * config.analogHands.secondHandLength).toInt()}" width="${config.analogHands.secondHandWidth.toInt()}" color="${config.analogHands.secondHandColor}">""")
                sb.appendLine("""                        <CenterPin radius="${config.analogHands.centerPinRadius.toInt()}" color="${config.analogHands.centerPinColor}" />""")
                sb.appendLine("""                    </HandDraw>""")
                sb.appendLine("""                </SecondHand>""")
                sb.appendLine("""            </Compare>""")
            }

            sb.appendLine("""        </AnalogClock>""")
        }

        // Ambient mode low-power layer overrides
        sb.appendLine()
        sb.appendLine("""        <!-- Ambient (AOD) Mode Directives (On-Pixel Ratio < 15%) -->""")
        sb.appendLine("""        <Compare expression="[IS_AMBIENT] == 1">""")
        sb.appendLine("""            <!-- Hollow/monochrome Ambient rendering to prevent AMOLED burn-in -->""")
        sb.appendLine("""            <PartDraw x="0" y="0" width="${config.shape.sizeDp}" height="${config.shape.sizeDp}">""")
        sb.appendLine("""                <Circle x="$half" y="$half" radius="${radius - 2}">""")
        sb.appendLine("""                    <Stroke color="#FFFFFF" thickness="1" />""")
        sb.appendLine("""                </Circle>""")
        sb.appendLine("""            </PartDraw>""")
        sb.appendLine("""        </Compare>""")

        // Dynamic Conditions & Expressions (Wear OS 6/7)
        if (config.targetWearOsVersion >= 6 && config.conditionRules.any { it.isEnabled }) {
            sb.appendLine()
            sb.appendLine("""        <!-- Wear OS 6/7 Dynamic Conditions & Expressions -->""")
            config.conditionRules.filter { it.isEnabled }.forEach { rule ->
                sb.appendLine("""        <!-- Rule: ${escapeXml(rule.title)} (${escapeXml(rule.conditionAction)}) -->""")
                sb.appendLine("""        <Compare expression="${escapeXml(rule.expression)}">""")
                sb.appendLine("""            <!-- Target: ${escapeXml(rule.targetProperty)} -->""")
                sb.appendLine("""        </Compare>""")
            }
        }

        sb.appendLine("""    </Scene>""")
        sb.appendLine("""</WatchFace>""")

        return sb.toString()
    }

    private fun generateComplicationSlotXml(
        sb: StringBuilder,
        slot: ComplicationSlotConfig,
        config: WatchFaceConfig
    ) {
        val center = config.shape.sizeDp / 2
        val angleDeg = slot.customAngle ?: slot.position.angleDeg
        val rFactor = slot.customRadiusFactor ?: slot.position.radiusFactor
        val radius = (center * rFactor)
        val rad = Math.toRadians(angleDeg.toDouble())
        val slotSize = 84
        val slotX = (center + radius * Math.cos(rad) - slotSize / 2).toInt()
        val slotY = (center + radius * Math.sin(rad) - slotSize / 2).toInt()

        val providerType = when (slot.dataSource) {
            SimulatedDataSource.BATTERY -> "BATTERY"
            SimulatedDataSource.STEPS -> "STEP_COUNT"
            SimulatedDataSource.HEART_RATE -> "HEART_RATE"
            SimulatedDataSource.WEATHER -> "WEATHER"
            SimulatedDataSource.CALORIES -> "CALORIES"
            SimulatedDataSource.NEXT_EVENT -> "NEXT_EVENT"
            SimulatedDataSource.SUNRISE_SUNSET -> "SUNRISE_SUNSET"
            SimulatedDataSource.UV_INDEX -> "UV_INDEX"
        }

        sb.appendLine("""        <!-- Slot #${slot.slotId}: ${slot.name} (${slot.position.displayName}) -->""")
        sb.appendLine(
            """        <ComplicationSlot id="${slot.slotId}" slotType="${slot.slotType.wffTagName}" supportedTypes="${slot.slotType.wffTagName} SHORT_TEXT" x="$slotX" y="$slotY" width="$slotSize" height="$slotSize">"""
        )
        sb.appendLine("""            <DefaultProviderPolicy defaultSystemProviderType="$providerType" />""")

        when (slot.slotType) {
            ComplicationType.RANGED_VALUE, ComplicationType.GOAL_PROGRESS -> {
                sb.appendLine("""            <RangedValueDisplay>""")
                sb.appendLine("""                <ArcMeter startAngle="135" endAngle="405" thickness="6" color="${slot.accentColor}" backgroundColor="#1E293B" />""")
                sb.appendLine("""                <ValueText format="[VALUE]">""")
                sb.appendLine("""                    <Font size="13" color="#FFFFFF" weight="BOLD" />""")
                sb.appendLine("""                </ValueText>""")
                sb.appendLine("""            </RangedValueDisplay>""")
            }
            ComplicationType.WEIGHTED_ARC -> {
                // Wear OS 7 Weighted Multi-Arc
                sb.appendLine("""            <WeightedArcDisplay segments="4" gap="4">""")
                sb.appendLine("""                <ArcSegment weight="25" color="${slot.accentColor}" />""")
                sb.appendLine("""                <ArcSegment weight="25" color="${config.secondaryColor}" />""")
                sb.appendLine("""                <ArcSegment weight="25" color="${config.tertiaryColor}" />""")
                sb.appendLine("""                <ArcSegment weight="25" color="#334155" />""")
                sb.appendLine("""            </WeightedArcDisplay>""")
            }
            ComplicationType.SHORT_TEXT -> {
                sb.appendLine("""            <ShortTextDisplay>""")
                sb.appendLine("""                <TitleText format="${slot.name.take(6).uppercase()}">""")
                sb.appendLine("""                    <Font size="10" color="${config.secondaryColor}" />""")
                sb.appendLine("""                </TitleText>""")
                sb.appendLine("""                <ValueText format="[VALUE]">""")
                sb.appendLine("""                    <Font size="14" color="#FFFFFF" weight="BOLD" />""")
                sb.appendLine("""                </ValueText>""")
                sb.appendLine("""            </ShortTextDisplay>""")
            }
            ComplicationType.ICON -> {
                sb.appendLine("""            <MonochromaticImage tintColor="${slot.accentColor}" />""")
            }
        }

        sb.appendLine("""        </ComplicationSlot>""")
    }

    private fun escapeXml(input: String): String {
        return input.replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace("\"", "&quot;")
            .replace("'", "&apos;")
    }
}
